const DEG = Math.PI / 180;

/** Сетка nx × ny по вырезке; веса костей считаются один раз, поза — каждый кадр (pose) */
export class Rig {
  /** only — учитывать только эти кости; skip — эти кости на лист не действуют */
  constructor(def, { only = null, skip = [] } = {}, nx = 120, ny = 104) {
    this.def = def;
    const use = b => !skip.includes(b.name) && (!only || only.includes(b.name));
    this.nx = nx; this.ny = ny;
    const A = def.aspect, n = (nx + 1) * (ny + 1);
    this.n = n;
    this.uv = new Float32Array(n * 2);        // доли вырезки (они же — координаты текстуры)
    this.rest = new Float32Array(n * 2);      // те же точки в «ровных» единицах (x × aspect) — для поворотов
    this.pos = new Float32Array(n * 2);       // после деформации, доли вырезки
    for (let j = 0, i = 0; j <= ny; j++) for (let k = 0; k <= nx; k++, i++) {
      this.uv[i * 2] = k / nx; this.uv[i * 2 + 1] = j / ny;
      this.rest[i * 2] = (k / nx) * A; this.rest[i * 2 + 1] = j / ny;
    }
    const idx = new Uint16Array(nx * ny * 6);
    for (let j = 0, t = 0; j < ny; j++) for (let k = 0; k < nx; k++) {
      const a = j * (nx + 1) + k, b = a + 1, c = a + nx + 1, d = c + 1;
      idx[t++] = a; idx[t++] = b; idx[t++] = c; idx[t++] = b; idx[t++] = d; idx[t++] = c;
    }
    this.index = idx;

    // веса: своя область + области потомков
    const dense = {};
    this.bones = def.bones.filter(use).map(b => {
      const w = new Float32Array(n);
      for (const [ax0, ay, bx0, by, r] of b.caps) {
        const ax = ax0 * A, bx = bx0 * A, dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy || 1e-9;
        for (let i = 0; i < n; i++) {
          const px = this.rest[i * 2], py = this.rest[i * 2 + 1];
          const t = Math.min(1, Math.max(0, ((px - ax) * dx + (py - ay) * dy) / len2));
          const d = Math.hypot(px - ax - dx * t, py - ay - dy * t);
          let v = 1 - Math.min(1, Math.max(0, (d - r) / b.f));
          v = v * v * (3 - 2 * v);
          if (v > w[i]) w[i] = v;
        }
      }
      for (const kid of b.kids || []) { const kw = dense[kid]; if (kw) for (let i = 0; i < n; i++) if (kw[i] > w[i]) w[i] = kw[i]; }
      // исключения: вес гасится внутри капсулы и на узкой кромке вокруг неё
      for (const [ax0, ay, bx0, by, r] of b.not || []) {
        const ax = ax0 * A, bx = bx0 * A, dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy || 1e-9;
        for (let i = 0; i < n; i++) {
          if (!w[i]) continue;
          const px = this.rest[i * 2], py = this.rest[i * 2 + 1];
          const t = Math.min(1, Math.max(0, ((px - ax) * dx + (py - ay) * dy) / len2));
          const d = Math.hypot(px - ax - dx * t, py - ay - dy * t);
          let v = Math.min(1, Math.max(0, (d - r) / 0.008));
          w[i] *= v * v * (3 - 2 * v);
        }
      }
      dense[b.name] = w;
      const ids = [], ws = [];
      for (let i = 0; i < n; i++) if (w[i] > 0.002) { ids.push(i); ws.push(w[i]); }
      return { name: b.name, wind: b.wind, fly: b.fly, px: b.pivot[0] * A, py: b.pivot[1], ids: Uint16Array.from(ids), ws: Float32Array.from(ws) };
    });
    this.pose(0, 0);
  }

  /** wind, fly — доли 0…1 (замах; полёт). Поворот вершины — угол кости × её вес: сустав гнётся плавно */
  pose(wind, fly) {
    const p = this.pos, A = this.def.aspect;
    p.set(this.rest);
    for (const b of this.bones) {
      const ang = (b.wind * wind + b.fly * fly) * DEG;
      if (Math.abs(ang) < 1e-5) continue;
      const { ids, ws, px, py } = b;
      for (let j = 0; j < ids.length; j++) {
        const i = ids[j] * 2, t = ang * ws[j], c = Math.cos(t), s = Math.sin(t);
        const dx = p[i] - px, dy = p[i + 1] - py;
        p[i] = px + dx * c - dy * s;
        p[i + 1] = py + dx * s + dy * c;
      }
    }
    for (let i = 0; i < p.length; i += 2) p[i] /= A;
    return p;
  }
}
